const zodHeader = `// Code generated by go test ./fakes/world -run TestManifestSchema -update. DO NOT EDIT.

import { z } from "zod";

`

// zodModule renders a schema invopop reflected as a TypeScript module that
// exports it as the zod schema name. It covers only the keywords invopop
// emits for the types it has met and refuses any other, so a new Go type
// that needs more fails here instead of loosening the TypeScript.
func zodModule(name string, s *jsonschema.Schema) (string, error) {
	expr, err := zodExpr(s, "#", "$schema")
	if err != nil {
		return "", err
	}
	return zodHeader + "export const " + name + " = " + expr + ";\n", nil
}

var zodKeywords = []string{"type", "enum", "items", "properties", "required", "additionalProperties"}

func zodExpr(s *jsonschema.Schema, at string, extra ...string) (string, error) {
	if err := covered(s, at, extra); err != nil {
		return "", err
	}
	switch s.Type {
	case "string":
		if len(s.Enum) == 0 {
			return "z.string()", nil
		}
		values := make([]string, len(s.Enum))
		for i, v := range s.Enum {
			str, ok := v.(string)
			if !ok {
				return "", fmt.Errorf("%s: enum value %v is not a string", at, v)
			}
			values[i] = tsString(str)
		}
		return "z.enum([" + strings.Join(values, ", ") + "])", nil
	case "integer":
		return "z.int()", nil
	case "number":
		return "z.number()", nil
	case "boolean":
		return "z.boolean()", nil
	case "array":
		if s.Items == nil {
			return "", fmt.Errorf("%s: array without items", at)
		}
		items, err := zodExpr(s.Items, at+"/items")
		if err != nil {
			return "", err
		}
		return call("z.array", items), nil
	case "object":
		return zodObject(s, at)
	}
	return "", fmt.Errorf("%s: type %q is not covered", at, s.Type)
}

func zodObject(s *jsonschema.Schema, at string) (string, error) {
	if s.Properties == nil {
		if s.AdditionalProperties == nil || s.AdditionalProperties == jsonschema.FalseSchema {
			return "", fmt.Errorf("%s: an object needs properties or an additionalProperties schema", at)
		}
		values, err := zodExpr(s.AdditionalProperties, at+"/additionalProperties")
		if err != nil {
			return "", err
		}
		return call("z.record", "z.string()", values), nil
	}
	if s.AdditionalProperties != jsonschema.FalseSchema {
		return "", fmt.Errorf("%s: an object with properties must forbid additional properties", at)
	}
	var b strings.Builder
	b.WriteString("z.strictObject({\n")
	for p := s.Properties.Oldest(); p != nil; p = p.Next() {
		expr, err := zodExpr(p.Value, at+"/properties/"+p.Key)
		if err != nil {
			return "", err
		}
		if !slices.Contains(s.Required, p.Key) {
			expr = call("z.optional", expr)
		}
		b.WriteString(indent(tsKey(p.Key)+": "+expr+",") + "\n")
	}
	b.WriteString("})")
	return b.String(), nil
}

// call lays out a call the way oxfmt does: on one line, or with every
// argument on its own line once any argument spans several.
func call(fn string, args ...string) string {
	if !slices.ContainsFunc(args, func(a string) bool { return strings.Contains(a, "\n") }) {
		return fn + "(" + strings.Join(args, ", ") + ")"
	}
	var b strings.Builder
	b.WriteString(fn + "(\n")
	for _, a := range args {
		b.WriteString(indent(a+",") + "\n")
	}
	b.WriteString(")")
	return b.String()
}

func indent(s string) string {
	return "  " + strings.ReplaceAll(s, "\n", "\n  ")
}

var tsIdentifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(k string) string {
	if tsIdentifier.MatchString(k) {
		return k
	}
	return tsString(k)
}

func tsString(s string) string {
	out, err := json.Marshal(s)
	if err != nil {
		panic(err)
	}
	return string(out)
}

// covered refuses a schema that carries a keyword zodExpr would drop.
func covered(s *jsonschema.Schema, at string, extra []string) error {
	data, err := json.Marshal(s)
	if err != nil {
		return fmt.Errorf("%s: %w", at, err)
	}
	var keywords map[string]json.RawMessage
	if err := json.Unmarshal(data, &keywords); err != nil {
		return fmt.Errorf("%s: %s is not an object schema", at, data)
	}
	for k := range keywords {
		if !slices.Contains(zodKeywords, k) && !slices.Contains(extra, k) {
			return fmt.Errorf("%s: keyword %q is not covered", at, k)
		}
	}
	return nil
}

func reflectSchema(v any) *jsonschema.Schema {
	return (&jsonschema.Reflector{Anonymous: true, DoNotReference: true}).Reflect(v)
}

func TestZodModule(t *testing.T) {
	type flags struct {
		On    bool                `json:"on"`
		Ratio float64             `json:"ratio,omitempty"`
		Paths map[string][]string `json:"paths"`
	}
	got, err := zodModule("flags", reflectSchema(flags{}))
	if err != nil {
		t.Fatal(err)
	}
	want := zodHeader + `export const flags = z.strictObject({
  on: z.boolean(),
  ratio: z.optional(z.number()),
  paths: z.record(z.string(), z.array(z.string())),
});
`
	if got != want {
		t.Fatalf("zodModule = %s\nwant %s", got, want)
	}
}

func TestZodModuleRefusesAKeywordItDoesNotCover(t *testing.T) {
	type named struct {
		Name string `json:"name" jsonschema:"pattern=^a"`
	}
	_, err := zodModule("named", reflectSchema(named{}))
	if want := `#/properties/name: keyword "pattern" is not covered`; err == nil || err.Error() != want {
		t.Fatalf("zodModule error = %v, want %s", err, want)
	}
}
