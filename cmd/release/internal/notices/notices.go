// Package notices generates the third-party notices file the release binary
// embeds and checks every shipped dependency's license against the policy.
package notices

import (
	"bytes"
	"cmp"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/jatassi/slipstream/cmd/release/internal/native"
)

const (
	policyPath      = "licenses.json"
	noticesPath     = "internal/notices/NOTICES.txt"
	generateCommand = "go run ./cmd/release notices generate"
	inputsPath      = "native/inputs.json"
	runtimesPath    = "native/runtimes.json"
	licensesDir     = "native/licenses"
)

type Source string

const (
	SourceGo      Source = "Go module"
	SourceNPM     Source = "npm package"
	SourceNative  Source = "native library"
	SourceRuntime Source = "toolchain runtime"
)

// Dependency is one third-party component the release binary carries on
// Targets, with the license text it ships under.
type Dependency struct {
	Source  Source
	Name    string
	Version string
	License string
	Targets []string
	Text    string
}

func (d Dependency) String() string {
	return fmt.Sprintf("%s %s %s", d.Source, d.Name, d.Version)
}

// Runtime is a toolchain library linked statically into the binary on Targets.
type Runtime struct {
	Name    string   `json:"name"`
	Version string   `json:"version"`
	License string   `json:"license"`
	Targets []string `json:"targets"`
}

// Generate collects every dependency the release binary ships for the
// targets in native/inputs.json, enforces the license policy and renders
// the notices file.
func Generate(root string) ([]byte, error) {
	in, err := native.LoadInputs(filepath.Join(root, inputsPath))
	if err != nil {
		return nil, err
	}
	policy, err := loadPolicy(filepath.Join(root, policyPath))
	if err != nil {
		return nil, err
	}
	goDeps, err := goModules(root, in.Targets)
	if err != nil {
		return nil, err
	}
	npmDeps, err := npmPackages(filepath.Join(root, "web"), targetNames(in.Targets))
	if err != nil {
		return nil, err
	}
	nativeDeps, err := nativeLibraries(root, in)
	if err != nil {
		return nil, err
	}
	deps := slices.Concat(goDeps, npmDeps, nativeDeps)
	if err := policy.enforce(deps); err != nil {
		return nil, err
	}
	return render(deps), nil
}

func Check(root string) error {
	want, err := Generate(root)
	if err != nil {
		return err
	}
	got, err := readText(filepath.Join(root, noticesPath))
	if err != nil {
		return err
	}
	if got != string(want) {
		return fmt.Errorf("%s is stale; run %s", noticesPath, generateCommand)
	}
	return nil
}

func Write(root string) error {
	data, err := Generate(root)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, noticesPath), data, 0o644)
}

func nativeLibraries(root string, in native.Inputs) ([]Dependency, error) {
	data, err := os.ReadFile(filepath.Join(root, runtimesPath))
	if err != nil {
		return nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var file struct {
		Runtimes []Runtime `json:"runtimes"`
	}
	if err := dec.Decode(&file); err != nil {
		return nil, fmt.Errorf("%s: %w", runtimesPath, err)
	}
	var deps []Dependency
	for _, c := range in.Components {
		deps = append(deps, Dependency{SourceNative, c.Name, c.Version, c.License, targetNames(in.Targets), ""})
	}
	for _, r := range file.Runtimes {
		deps = append(deps, Dependency{SourceRuntime, r.Name, r.Version, r.License, r.Targets, ""})
	}
	for i := range deps {
		text, err := readText(filepath.Join(root, licensesDir, deps[i].Name+".txt"))
		if err != nil {
			return nil, err
		}
		deps[i].Text = text
	}
	return deps, nil
}

func targetNames(targets []native.Target) []string {
	names := make([]string, len(targets))
	for i, t := range targets {
		names[i] = t.Name
	}
	return names
}

func readText(path string) (string, error) {
	data, err := os.ReadFile(path)
	return strings.ReplaceAll(string(data), "\r\n", "\n"), err
}

const header = `Third-party notices for SlipStream

SlipStream is licensed under GPL-3.0. The release binary also carries the
components below, each under its own license. This file is generated by
` + generateCommand + `; do not edit it.
`

func render(deps []Dependency) []byte {
	slices.SortFunc(deps, func(a, b Dependency) int {
		return cmp.Or(cmp.Compare(a.Name, b.Name), cmp.Compare(a.Version, b.Version), cmp.Compare(a.Source, b.Source))
	})
	var b strings.Builder
	b.WriteString(header)
	for _, d := range deps {
		fmt.Fprintf(&b, "\n%s\n%s %s (%s)\nLicense: %s\nTargets: %s\n",
			strings.Repeat("=", 80), d.Name, d.Version, d.Source, d.License, strings.Join(d.Targets, ", "))
		if text := strings.TrimSpace(d.Text); text != "" {
			fmt.Fprintf(&b, "\n%s\n", text)
		}
	}
	return []byte(b.String())
}
