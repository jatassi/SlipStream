package rules

import (
	"go/ast"
	"path"
	"strings"

	"github.com/jatassi/slipstream/cmd/release/internal/lint"
)

func init() {
	lint.Register(lint.Rule{
		Name:  "sqlc-generated",
		Doc:   "sqlc's output lives in <owner>/internal/db, with typed ids and storage.Time for every _at column (spec #128, Typed ids, UTC times and row order)",
		Check: checkSqlcGenerated,
	})
}

const sqlcHeader = "// Code generated by sqlc. DO NOT EDIT."

func sqlcGenerated(f lint.GoFile) bool {
	for _, group := range f.Syntax.Comments {
		if group.Pos() > f.Syntax.Package {
			break
		}
		for _, c := range group.List {
			if c.Text == sqlcHeader {
				return true
			}
		}
	}
	return false
}

func checkSqlcGenerated(repo *lint.Repo) ([]lint.Finding, error) {
	module, err := modulePath(repo)
	if err != nil {
		return nil, err
	}
	tracked, err := repo.Files()
	if err != nil {
		return nil, err
	}
	sqlcConfigs := map[string]bool{}
	for _, f := range tracked {
		if path.Base(f) == "sqlc.yaml" {
			sqlcConfigs[path.Dir(f)] = true
		}
	}
	files, err := productFiles(repo)
	if err != nil {
		return nil, err
	}
	var findings []lint.Finding
	for _, f := range files {
		if !sqlcGenerated(f) {
			continue
		}
		if owner, ok := strings.CutSuffix(path.Dir(f.Path), "/internal/db"); !ok || !sqlcConfigs[owner] {
			findings = append(findings, lint.Finding{Path: f.Path, Line: 1, Message: "generated output outside <owner>/internal/db; set out: internal/db in the owner's sqlc.yaml"})
		}
		types := generatedTypes{imports: importNames(f), storage: module + "/internal/storage"}
		findings = append(findings, types.fieldFindings(repo, f)...)
	}
	return findings, nil
}

type generatedTypes struct {
	imports map[string]string
	storage string
}

func (g generatedTypes) fieldFindings(repo *lint.Repo, f lint.GoFile) []lint.Finding {
	var findings []lint.Finding
	ast.Inspect(f.Syntax, func(n ast.Node) bool {
		field, ok := n.(*ast.Field)
		if !ok {
			return true
		}
		for _, name := range field.Names {
			if msg := g.check(name.Name, field.Type); msg != "" {
				findings = append(findings, lint.Finding{Path: f.Path, Line: repo.Fset.Position(name.Pos()).Line, Message: msg})
			}
		}
		return true
	})
	return findings
}

func (g generatedTypes) check(name string, typ ast.Expr) string {
	const (
		typedID     = "give the column a typed id override in sqlc.yaml"
		storageTime = "_at columns map to storage.Time"
	)
	pkg, sel := g.qualified(typ)
	switch {
	case (name == "id" || strings.HasSuffix(name, "ID")) && untypedID(typ, pkg, sel):
		return typedID
	case pkg == "time" && sel == "Time", pkg == "database/sql" && sel == "NullTime":
		return storageTime
	case strings.HasSuffix(name, "At") && (pkg != g.storage || sel != "Time"):
		return storageTime
	}
	return ""
}

func untypedID(typ ast.Expr, pkg, sel string) bool {
	switch t := typ.(type) {
	case *ast.Ident:
		return t.Name == "int64" || t.Name == "string"
	case *ast.ArrayType:
		elem, ok := t.Elt.(*ast.Ident)
		return t.Len == nil && ok && elem.Name == "byte"
	}
	return pkg == "database/sql" && strings.HasPrefix(sel, "Null")
}

func (g generatedTypes) qualified(typ ast.Expr) (pkg, name string) {
	sel, ok := typ.(*ast.SelectorExpr)
	if !ok {
		return "", ""
	}
	x, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", ""
	}
	return g.imports[x.Name], sel.Sel.Name
}
