func TestPlatformTests(t *testing.T) {
	const missing = " has OS-specific code and no test in the platform suite. Add a test that runs this code to " + platformRegistry + "."
	goosEquals := "package p\n\nimport \"runtime\"\n\nvar windows = runtime.GOOS == \"windows\"\n"
	declares := map[string]string{"p/p_test.go": "package p\n\nimport \"testing\"\n\nfunc TestMain(m *testing.M) {}\n\nfunc TestOpen(t *testing.T) {}\n"}
	for _, tt := range []struct {
		name  string
		files map[string]string
		tests []platform.Test
		want  []string
	}{
		{"an OS in the file name", map[string]string{"p/open_windows.go": "package p\n"}, nil, []string{"p/open_windows.go:1: p" + missing}},
		{"an OS and an arch in the file name", map[string]string{"p/open_darwin_arm64.go": "package p\n"}, nil, []string{"p/open_darwin_arm64.go:1: p" + missing}},
		{"unix in the file name", map[string]string{"p/open_unix.go": "package p\n"}, nil, []string{"p/open_unix.go:1: p" + missing}},
		{"an OS in a test file's name", map[string]string{"p/open_linux_test.go": "package p\n"}, nil, []string{"p/open_linux_test.go:1: p" + missing}},
		{"an OS build constraint", map[string]string{"p/open.go": "// Open files.\n\n//go:build !windows\n\npackage p\n"}, nil, []string{"p/open.go:3: p" + missing}},
		{"an OS build constraint in a test file", map[string]string{"p/open_test.go": "//go:build darwin || linux\n\npackage p\n"}, nil, []string{"p/open_test.go:1: p" + missing}},
		{"a GOOS comparison", map[string]string{"p/open.go": goosEquals}, nil, []string{"p/open.go:5: p" + missing}},
		{"a switch on GOOS", map[string]string{"p/open.go": "package p\n\nimport \"runtime\"\n\nfunc f() {\n\tswitch runtime.GOOS {\n\tcase \"darwin\":\n\t}\n}\n"}, nil, []string{"p/open.go:6: p" + missing}},
		{"GOOS named, not compared", map[string]string{"p/open.go": "package p\n\nimport \"runtime\"\n\nvar target = runtime.GOOS + \"-\" + runtime.GOARCH\n"}, nil, nil},
		{"a GOOS comparison in a test file", map[string]string{"p/open_test.go": goosEquals}, nil, nil},
		{"an arch in the file name", map[string]string{"p/open_amd64.go": "package p\n"}, nil, nil},
		{"an OS mid-name", map[string]string{"p/linux_open.go": "package p\n"}, nil, nil},
		{"a build constraint without an OS", map[string]string{"p/open.go": "//go:build cgo && !race\n\npackage p\n"}, nil, nil},
		{"testdata", map[string]string{"p/testdata/open_windows.go": "package p\n"}, nil, nil},
		{"generated code", map[string]string{"p/open.go": "// Code generated by gen. DO NOT EDIT.\n\n//go:build linux\n\npackage p\n"}, nil, nil},
		{
			"registered",
			mapsOf(declares, map[string]string{"p/open_windows.go": "package p\n"}),
			[]platform.Test{{Package: "p", Run: "^TestOpen$"}},
			nil,
		},
		{
			"covered by another package's test",
			mapsOf(declares, map[string]string{"q/open_windows.go": "package q\n"}),
			[]platform.Test{{Package: "p", Run: "^TestOpen$", Covers: []string{"q"}}},
			nil,
		},
		{
			"an entry that runs none of its package's tests",
			mapsOf(declares, map[string]string{"p/open_windows.go": "package p\n"}),
			[]platform.Test{{Package: "p", Run: "^(TestClose|TestMain)$"}},
			[]string{platformRegistry + `:1: The entry for p runs "^(TestClose|TestMain)$", which matches none of its tests. Name a test the package declares.`},
		},
		{
			"an entry that isn't a regular expression",
			declares,
			[]platform.Test{{Package: "p", Run: "^(TestOpen$"}},
			[]string{platformRegistry + `:1: The entry for p runs "^(TestOpen$", which isn't a regular expression.`},
		},
		{
			"an entry that covers a package with no OS-specific code",
			mapsOf(declares, map[string]string{"q/q.go": "package q\n"}),
			[]platform.Test{{Package: "p", Run: "^TestOpen$", Covers: []string{"q"}}},
			[]string{platformRegistry + ":1: The entry for p covers q, which has no OS-specific code. Remove it from Covers."},
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			findings, err := checkPlatformTests(repoOf(t, tt.files), tt.tests)
			if err != nil {
				t.Fatal(err)
			}
			var got []string
			for _, f := range findings {
				got = append(got, fmt.Sprintf("%s:%d: %s", f.Path, f.Line, f.Message))
			}
			if !slices.Equal(got, tt.want) {
				t.Errorf("findings:\n%q\nwant:\n%q", got, tt.want)
			}
		})
	}
}

func mapsOf(a, b map[string]string) map[string]string {
	m := maps.Clone(a)
	maps.Copy(m, b)
	return m
}

func repoOf(t *testing.T, files map[string]string) *lint.Repo {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	for name, src := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.CommandContext(t.Context(), "git", args...)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	return lint.Open(t.Context(), root)
}
