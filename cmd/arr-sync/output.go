package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// tree is everything one run writes, by repository path. The lever owns
// every file under owned except the golden harness's pending and
// overrides lists, so a file it no longer writes is deleted.
type tree struct {
	files map[string][]byte
	owned []string
}

func (t *tree) add(path string, content []byte) {
	t.files[path] = content
}

func (t *tree) own(dir string) {
	t.owned = append(t.owned, dir)
}

func handKept(name string) bool {
	return strings.HasSuffix(name, ".pending.json") || strings.HasSuffix(name, ".overrides.json")
}

// write makes the repository match t and returns the paths it changed.
func (t *tree) write(root *os.Root) ([]string, error) {
	owned, err := filesUnder(root, t.owned)
	if err != nil {
		return nil, err
	}
	var changed []string
	for _, file := range owned {
		if _, ok := t.files[file]; ok || handKept(file) {
			continue
		}
		if err := root.Remove(filepath.FromSlash(file)); err != nil {
			return nil, fmt.Errorf("remove %s: %w", file, err)
		}
		changed = append(changed, file)
	}
	for file, content := range t.files {
		name := filepath.FromSlash(file)
		if old, err := root.ReadFile(name); err == nil && bytes.Equal(old, content) {
			continue
		}
		if err := root.MkdirAll(filepath.Dir(name), 0o750); err != nil {
			return nil, fmt.Errorf("write %s: %w", file, err)
		}
		if err := root.WriteFile(name, content, 0o600); err != nil {
			return nil, fmt.Errorf("write %s: %w", file, err)
		}
		changed = append(changed, file)
	}
	slices.Sort(changed)
	return changed, nil
}

// filesUnder lists every file under each of paths, a file listing itself,
// as slash-separated paths in the repository.
func filesUnder(root *os.Root, paths []string) ([]string, error) {
	var files []string
	for _, p := range paths {
		err := fs.WalkDir(root.FS(), p, func(file string, d fs.DirEntry, err error) error {
			switch {
			case errors.Is(err, fs.ErrNotExist):
				return nil
			case err != nil:
				return err
			case !d.IsDir():
				files = append(files, file)
			}
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("list %s: %w", p, err)
		}
	}
	return files, nil
}

const (
	generatedPrefix = "// Code generated by cmd/arr-sync"
	digestPrefix    = "// Digest: sha256:"
)

// goFile is a generated Go file: a header naming the upstream sources it
// was read from and the digest of the formatted body below it, so a hand
// edit or a pin bump without a rerun fails the drift test.
func goFile(sources []checkout, paths []string, body string) ([]byte, error) {
	formatted, err := format.Source([]byte(body))
	if err != nil {
		return nil, fmt.Errorf("format the generated code: %w\n%s", err, body)
	}
	names := make([]string, len(sources))
	for i, c := range sources {
		names[i] = c.Name + " " + c.Commit
	}
	from := ""
	if len(names) > 0 {
		from = " from " + strings.Join(names, " and ")
	}
	if len(paths) > 0 {
		from += ": " + strings.Join(paths, ", ")
	}
	sum := sha256.Sum256(formatted)
	header := generatedPrefix + from + ". DO NOT EDIT.\n" + digestPrefix + hex.EncodeToString(sum[:]) + "\n\n"
	return append([]byte(header), formatted...), nil
}
