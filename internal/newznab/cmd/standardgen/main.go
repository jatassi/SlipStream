// Command standardgen writes internal/newznab/standard.go from Prowlarr's
// NewznabStandardCategory.cs, so a ported site's category table names
// each standard category as its C# does:
//
//	go run ./internal/newznab/cmd/standardgen -prowlarr <checkout>
package main

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const source = "src/NzbDrone.Core/Indexers/NewznabStandardCategory.cs"

func main() {
	prowlarr := flag.String("prowlarr", "", "a Prowlarr checkout")
	out := flag.String("out", filepath.Join("internal", "newznab", "standard.go"), "the file to write")
	flag.Parse()
	if err := run(*prowlarr, *out); err != nil {
		fmt.Fprintln(os.Stderr, "standardgen:", err)
		os.Exit(1)
	}
}

func run(prowlarr, out string) error {
	if prowlarr == "" {
		return errors.New("name a Prowlarr checkout with -prowlarr")
	}
	cs, err := os.ReadFile(filepath.Join(prowlarr, filepath.FromSlash(source))) //nolint:gosec // G304: the checkout the developer named
	if err != nil {
		return fmt.Errorf("read the category file: %w", err)
	}
	commit, err := exec.CommandContext(context.Background(), "git", "-C", prowlarr, "rev-parse", "--short=8", "HEAD").Output() //nolint:gosec // G204: the checkout the developer named
	if err != nil {
		return fmt.Errorf("read the checkout's commit: %w", err)
	}
	src, err := generate(cs, strings.TrimSpace(string(commit)))
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, src, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}
	return nil
}

var (
	member   = regexp.MustCompile(`public static readonly IndexerCategory (\w+) = new\((\d+), "([^"]+)"\);`)
	allCats  = regexp.MustCompile(`(?s)IndexerCategory\[\] AllCats =\s*\{(.*?)\};`)
	children = regexp.MustCompile(`(?s)(\w+)\.SubCategories\.AddRange\(\s*new List<IndexerCategory>\s*\{(.*?)\}`)
	name     = regexp.MustCompile(`\w+`)
)

type category struct {
	name, label string
	id, parent  int
}

// generate is standard.go for the C# file cs at commit.
func generate(cs []byte, commit string) ([]byte, error) {
	var members []*category
	byName := map[string]*category{}
	for _, m := range member.FindAllSubmatch(cs, -1) {
		id, err := strconv.Atoi(string(m[2]))
		if err != nil {
			return nil, fmt.Errorf("member %s: %w", m[1], err)
		}
		c := &category{name: string(m[1]), label: string(m[3]), id: id}
		members, byName[c.name] = append(members, c), c
	}
	for _, m := range children.FindAllSubmatch(cs, -1) {
		parent, ok := byName[string(m[1])]
		if !ok {
			return nil, fmt.Errorf("subcategories of unknown member %s", m[1])
		}
		for _, child := range name.FindAll(m[2], -1) {
			c, ok := byName[string(child)]
			if !ok {
				return nil, fmt.Errorf("unknown subcategory %s of %s", child, parent.name)
			}
			c.parent = parent.id
		}
	}
	all := allCats.FindSubmatch(cs)
	if len(members) == 0 || all == nil {
		return nil, errors.New("the file declares no categories or no AllCats")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/newznab/cmd/standardgen from Prowlarr's %s at %s. DO NOT EDIT.\n\n", source, commit)
	b.WriteString("package newznab\n\n// NewznabStandardCategory's members, by their C# names.\nvar (\n")
	for _, c := range members {
		fmt.Fprintf(&b, "\t%s = Category{ID: %d, Name: %q, Parent: %d}\n", c.name, c.id, c.label, c.parent)
	}
	b.WriteString(")\n\n// allCats is NewznabStandardCategory.AllCats in its order, so a lookup by\n// name finds the entry Prowlarr's does: Other is 8000, not 0.\nvar allCats = []Category{\n")
	for _, n := range name.FindAll(all[1], -1) {
		if byName[string(n)] == nil {
			return nil, fmt.Errorf("AllCats names unknown member %s", n)
		}
		fmt.Fprintf(&b, "\t%s,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format standard.go: %w", err)
	}
	return src, nil
}
