import { boxCorners, fitProjection } from "@anatomy/iso-kit";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import * as A from "../vendor/anatomy/kit/audit.mjs";
import { itemsOf } from "../src/diagram/geometry";
import { AZIMUTH, TILE } from "../src/diagram/layout";
import type { NodeRow } from "../src/routes/_app/nodes/-landing/view";
import { recorderFor, record, say } from "./diagram-record";

// Settles one canonical tile holding every Role, so every chip and machine is
// on it, and writes each part's depth key. A part's key is the same at every
// place and scale, so the Diagram sorts each tile's parts by these keys.

const OUT = fileURLToPath(new URL("../src/diagram/keys.gen.ts", import.meta.url));

const roles = [
  "searching",
  "downloading",
  "storage",
  "converting",
  "subtitles",
  "metadata",
  "media-server-link",
  "notifying",
  "relaying",
  "serving",
] as const;

const canonical: NodeRow = {
  id: "canonical",
  name: "canonical",
  controller: true,
  state: "online",
  facts: [],
  roles: roles.map((role) => ({
    role,
    label: role,
    state: "holding",
    note: "holding",
    words: role,
  })),
  findings: [],
  holds: false,
  plaque: "Online",
  torrents: [],
};

const P = fitProjection(boxCorners(TILE, 0, 180), 1100, 900, { pad: 24, azimuth: AZIMUTH });
const R = recorderFor(P);
for (const item of itemsOf(P, canonical)) {
  record(R, item);
}
const { items } = A.settle(R);
const keys = items
  .map(({ name, key }) => [name, Math.round(key * 1000) / 1000] as const)
  .toSorted(([a], [b]) => a.localeCompare(b));

const text = [
  "// Generated by scripts/diagram-keys.ts from one settled canonical tile. Do not edit.",
  "export const KEYS: Readonly<Record<string, number>> = {",
  ...keys.map(([name, key]) => `  "${name}": ${String(key)},`),
  "};",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    say("web/src/diagram/keys.gen.ts is stale: run bun run diagram:keys");
    process.exit(1);
  }
  say("diagram keys are current");
} else {
  writeFileSync(OUT, text);
  say(`wrote ${String(keys.length)} depth keys`);
}
